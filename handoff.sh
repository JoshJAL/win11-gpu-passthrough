#!/bin/bash
# Describe this machine to a coding agent and point it at the bundle folders that match.
#
#   ./handoff.sh                 write HANDOFF.local.md (gitignored) and print its path
#   ./handoff.sh --stdout        print it instead of writing a file
#   ./handoff.sh --profile-file FILE
#                                read a saved `detect.sh --profile` output instead of running it (tests,
#                                "what would a Debian + GNOME + AMD box get")
#
# It runs ./detect.sh --profile (read-only, no root), then resolves one folder per axis:
#   distros/<os-release ID>   (ID, then each ID_LIKE word; omarchy -> arch)
#   desktops/<compositor>
#   hardware/<host-gpu>-host_<passthrough-gpu>-pt
# An axis with no folder is a GAP: the agent fills in a copy of that axis's _template/ in its PR.
# The profile holds hardware and distro facts only: no user or host name, serial, UUID, MAC or IP.
set -u

B=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=lib/bundle.sh
. "$B/lib/bundle.sh"

die() { echo "handoff.sh: $*" >&2; exit 1; }

OUT=$B/HANDOFF.local.md STDOUT=0 PROFILE_FILE=
while [[ $# -gt 0 ]]; do
  case $1 in
    --stdout) STDOUT=1 ;;
    --profile-file) PROFILE_FILE=${2:?--profile-file needs a file}; shift ;;
    -h|--help) sed -n '2,13p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown argument: $1 (see --help)" ;;
  esac
  shift
done

# ---- profile ------------------------------------------------------------------------------------
if [[ -n $PROFILE_FILE ]]; then
  [[ -r $PROFILE_FILE ]] || die "cannot read $PROFILE_FILE"
  raw=$(cat "$PROFILE_FILE")
else
  raw=$("$B/detect.sh" --profile 2>/dev/null) || true   # exit 1 = a NO-GO finding; the profile is still complete
fi
declare -A P=()
while IFS= read -r line; do
  [[ $line =~ ^([A-Z][A-Z0-9_]*)=(.*)$ ]] && P[${BASH_REMATCH[1]}]=${BASH_REMATCH[2]}
done <<<"$raw"
[[ -n ${P[PROFILE_VERSION]:-} ]] || die "no profile from detect.sh --profile (is this Linux with /proc and /sys?)"
g() { printf '%s' "${P[$1]:-unknown}"; }

# ---- resolve the three axes -----------------------------------------------------------------------
tried=()                 # distro ids tried, in order
distro_dir= distro_id=
while IFS= read -r id; do
  tried+=("$id")
  if [[ -z $distro_id ]] && bundle_dir "$B" distros "$id" >/dev/null; then distro_id=$id; fi
done < <(
  # Same chain as install.sh, but from the profile so --profile-file can stand in for the machine.
  for w in ${P[DISTRO_ID]:-} ${P[DISTRO_ID_LIKE]:-}; do valid_id "$w" && printf '%s\n' "$w"; done
)
desktop_id=${P[DESKTOP]:-unknown}
if [[ $desktop_id != unknown ]] && bundle_dir "$B" desktops "$desktop_id" >/dev/null; then :; else desk_gap=1; fi
hw_key=none
if [[ -n ${P[HOST_GPU_VENDOR]:-} && ${P[PT_GPU_VENDOR]:-none} != none && ${P[HOST_GPU_VENDOR]} != none ]]; then
  hw_key=${P[HOST_GPU_VENDOR]}-host_${P[PT_GPU_VENDOR]}-pt
fi
hw_gap=0
if [[ $hw_key == none ]] || ! bundle_dir "$B" hardware "$hw_key" >/dev/null; then hw_gap=1; fi

folder_line() {  # folder_line <axis> <id> <found 0|1> <what to name a new folder>
  if [[ $3 == 1 ]]; then printf '| %s | `%s` | `%s/%s/` |\n' "$1" "$2" "$1" "$2"
  else printf '| %s | `%s` | **GAP**: no folder yet |\n' "$1" "$2"; fi
}

emit() {
  cat <<EOF
# Handoff: this machine

Generated by \`./handoff.sh\` on $(date +%Y-%m-%d). Local only (gitignored): do not commit or paste it into a
PR as is. It holds hardware and distro facts only; if you add anything else, run
\`tools/privacy-check.sh --files <file>\` on it first.

**Read next:** \`AGENTS.md\` (rules and the tier gates), then \`FOR_AGENT.md\` (the runbook), then the folders below.

## Verdict

\`$(g VERDICT)\` from \`./detect.sh\` ($(g NOGO_COUNT) blocker(s), $(g WARN_COUNT) warning(s)).
EOF
  local i n=${P[NOGO_COUNT]:-0}
  if [[ $n =~ ^[0-9]+$ ]] && (( n > 0 )); then
    echo
    echo 'Blockers (the human decides what to do; testing stays at tier T0, a T0-only report is a valid PR):'
    for ((i = 1; i <= n; i++)); do echo "- ${P[NOGO_$i]:-?}"; done
  fi
  cat <<EOF

## This machine

| | |
|---|---|
| Distro | $(g DISTRO_ID) $(g DISTRO_VERSION_ID) (ID_LIKE: ${P[DISTRO_ID_LIKE]:-none}) |
| Kernel / init | $(g KERNEL), $(g INIT) |
| Bootloader / firewall / packages | $(g BOOTLOADER) / $(g FIREWALL) / $(g PKG_MANAGER) |
| Desktop / session | $(g DESKTOP) / $(g SESSION_TYPE) |
| Machine | $(g SYS_VENDOR) $(g PRODUCT_NAME) ($(g FORM_FACTOR)) |
| CPU | $(g CPU_MODEL), $(g CPU_PHYS_BITS) physical address bits |
| IOMMU | $(g IOMMU) ($(g IOMMU_VENDOR)), address width $(g IOMMU_MGAW) bits |
| Host GPU | $(g HOST_GPU_MODEL) ($(g HOST_GPU_VENDOR)) at $(g HOST_GPU_PCI) |
| Passthrough GPU | $(g PT_GPU_MODEL) ($(g PT_GPU_VENDOR)) at $(g PT_GPU_PCI); IOMMU group isolated: $(g PT_GROUP_ISOLATED) |
| Displays | $(g DISPLAYS_HOST) on the host GPU side, $(g DISPLAYS_ON_PT_GPU) on the passthrough GPU |
| RAM / image fs | $(g RAM_GIB) GiB / $(g IMAGE_FS) |
| libvirt / QEMU / Looking Glass | $(g LIBVIRT_VERSION) / $(g QEMU_VERSION) / $(g LOOKING_GLASS_VERSION) |

## Matching folders

| Axis | Resolved to | Folder |
|---|---|---|
EOF
  if [[ -n $distro_id ]]; then folder_line distros "$distro_id" 1
  else folder_line distros "${tried[*]:-${P[DISTRO_ID]:-unknown}}" 0; fi
  if [[ ${desk_gap:-0} == 0 ]]; then folder_line desktops "$desktop_id" 1; else folder_line desktops "$desktop_id" 0; fi
  if [[ $hw_gap == 0 ]]; then folder_line hardware "$hw_key" 1
  elif [[ $hw_key == none ]]; then echo '| hardware | `none` | **no passthrough candidate** (see the blockers above) |'
  else folder_line hardware "$hw_key" 0; fi
  echo
  echo 'Read each matching folder'"'"'s `README.md` before you act: it lists what differs on that axis, the status, and known issues.'
  if [[ -n $distro_id && ${#tried[@]} -gt 0 && ${tried[0]} != "$distro_id" ]]; then
    echo "The distro folder came from ID_LIKE: \`${tried[0]}\` has no folder, \`$distro_id\` does."
  fi

  local gaps=0
  if [[ -z $distro_id ]]; then
    gaps=1
    cat <<EOF

### Gap: distro

No \`distros/\` folder matches (tried: ${tried[*]:-none}). \`install.sh\` stops until one exists. In your PR:

1. \`cp -r distros/_template distros/${tried[0]:-<ID>}\` (use the \`ID=\` from \`/etc/os-release\`)
2. Write \`distro.sh\` (packages, firewall rules, IOMMU boot hint) and fill in the README.
3. Check with \`./install.sh --check\` and \`./detect.sh\`.
EOF
  fi
  if [[ ${desk_gap:-0} == 1 ]]; then
    gaps=1
    if [[ $desktop_id == unknown ]]; then
      cat <<'EOF'

### Gap: desktop

The desktop could not be detected (XDG_CURRENT_DESKTOP is empty, for example over SSH). Ask the human which
desktop or compositor they run, then use its name (lowercase) for the folder.
EOF
    else
      cat <<EOF

### Gap: desktop

No \`desktops/$desktop_id/\` folder. Whether this desktop needs anything is the question: does the compositor open
the passthrough GPU, and what keeps it off the GPU while the VM owns it? In your PR:

1. \`cp -r desktops/_template desktops/$desktop_id\`
2. Fill in the README (and add a config snippet if one is needed; see \`desktops/hyprland/\`).
EOF
    fi
  fi
  if [[ $hw_gap == 1 && $hw_key != none ]]; then
    gaps=1
    cat <<EOF

### Gap: hardware

No \`hardware/$hw_key/\` folder. In your PR:

1. \`cp -r hardware/_template hardware/$hw_key\`
2. Fill in what is specific to this GPU pairing (reset behaviour, driver checks in the guest, address width,
   display wiring), linking \`LESSONS.md\` entries or your report.
EOF
  fi
  (( gaps )) && echo && echo 'A folder copied from a `_template` starts as "untested": its Status line must say which tier your report reached.'

  cat <<'EOF'

## What to do now

1. `./verify.sh` runs tier **T0** (read-only checks); no question needed.
2. Tiers **T1** (host install), **T2** (VM + Windows) and **T3** (GPU, USB, Looking Glass) each change the
   machine: ask the human before each one, then `./verify.sh --yes-tier N`. A tier cannot run until the one
   before it passed. Starting the VM and plugging USB devices are separate asks inside T2 and T3.
3. `tools/report.sh` writes the report under `reports/` from the profile and results; run
   `tools/privacy-check.sh` over everything, show the human the diff, and only then push a branch and open a
   PR. Never push to `main`; only the repository owner merges.
EOF
}

if (( STDOUT )); then emit; else emit >"$OUT" && echo "$OUT"; fi
